        ("Diagnostic", "Lire les informations firmware", ["dualsensectl", "info"]),
        ("Lightbar", "Allumer la barre lumineuse", ["dualsensectl", "lightbar", "on"]),
        ("Lightbar", "Éteindre la barre lumineuse", ["dualsensectl", "lightbar", "off"]),
        ("Lightbar", "Couleur RGB (PlayStation Blue)", ["dualsensectl", "lightbar", "0", "112", "209"]),
        ("Lightbar", "Couleur RGB + Luminosité", ["dualsensectl", "lightbar", "0", "240", "255", "200"]),
        ("LEDs", "Gradation des LEDs (High: 0)", ["dualsensectl", "led-brightness", "0"]),
        ("LEDs", "Gradation des LEDs (Medium: 1)", ["dualsensectl", "led-brightness", "1"]),
        ("LEDs", "Gradation des LEDs (Dim: 2)", ["dualsensectl", "led-brightness", "2"]),
        ("LEDs Joueur", "Indicateur Joueur 1 (instantané)", ["dualsensectl", "player-leds", "1", "instant"]),
        ("LEDs Joueur", "Indicateur Joueur 2", ["dualsensectl", "player-leds", "2", "instant"]),
        ("LEDs Joueur", "Indicateur Joueur 3", ["dualsensectl", "player-leds", "3", "instant"]),
        ("LEDs Joueur", "Désactiver LEDs joueurs (0)", ["dualsensectl", "player-leds", "0"]),
        ("Microphone", "Activer le microphone", ["dualsensectl", "microphone", "on"]),
        ("Microphone", "Couper le microphone (Mute)", ["dualsensectl", "microphone", "off"]),
        ("LED Micro", "LED Micro fixe (orange mute)", ["dualsensectl", "microphone-led", "on"]),
        ("LED Micro", "LED Micro éteinte", ["dualsensectl", "microphone-led", "off"]),
