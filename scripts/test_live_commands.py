"""
Test battery script to execute and validate all dualsensectl commands.
Checks CLI command compliance, parameter clamping, UI dispatch, and subprocess calls.
"""

import sys
import shutil
import subprocess
from typing import List, Tuple

# Color ANSI escapes
GREEN = "\033[92m"
BLUE = "\033[94m"
CYAN = "\033[96m"
YELLOW = "\033[93m"
RED = "\033[91m"
BOLD = "\033[1m"
RESET = "\033[0m"


def print_banner(text: str):
    print(f"\n{BOLD}{CYAN}{'='*80}{RESET}")
    print(f"{BOLD}{CYAN}  {text}{RESET}")
    print(f"{BOLD}{CYAN}{'='*80}{RESET}")


