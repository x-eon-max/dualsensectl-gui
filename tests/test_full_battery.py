class TestDualSenseCLICompliance(unittest.TestCase):
    """
    Validates that every command generated by the wrapper matches the exact
    grammar and options supported by /usr/bin/dualsensectl.
    """

    @classmethod
    def setUpClass(cls):
        cls.bin_path = shutil.which("dualsensectl")
        cls.has_bin = cls.bin_path is not None
        if cls.has_bin:
            # Extract all binary strings to verify supported command names
            cls.binary_strings = subprocess.check_output(["strings", cls.bin_path]).decode(errors="ignore")
        else:
            cls.binary_strings = ""

    def setUp(self):
        self.wrapper = DualSenseCTLWrapper(executable_path="dualsensectl", simulation_mode=True)
        self.wrapper._command_history.clear()

    def test_dualsensectl_binary_installed(self):
        """Verifies dualsensectl binary exists on the system."""
        self.assertTrue(self.has_bin, "dualsensectl is not installed on the system")

    def test_core_commands_exist_in_binary(self):
        """Checks that all subcommands implemented exist in the binary's symbol/string table."""
        expected_commands = [
            "power-off", "battery", "info", "lightbar", "led-brightness",
            "player-leds", "microphone", "microphone-led", "microphone-mode",
            "speaker", "volume", "attenuation", "trigger"
        ]
        for cmd in expected_commands:
            self.assertIn(cmd, self.binary_strings, f"Command '{cmd}' not found in binary strings")

    def test_trigger_modes_exist_in_binary(self):
        """Checks that all 7 trigger modes exist in dualsensectl binary."""
        expected_modes = [
            "feedback", "weapon", "bow", "galloping", "machine", "vibration", "off"
        ]
        for m in expected_modes:
            self.assertIn(m, self.binary_strings, f"Trigger mode '{m}' not found in binary strings")

    def test_command_device_targeting_flag(self):
        """Checks that -d <device> is placed right after the executable."""
        self.wrapper.set_lightbar_state(True, device_id="hidraw3")
        last_cmd = self.wrapper._command_history[-1]
        self.assertTrue(last_cmd.startswith("dualsensectl -d hidraw3 lightbar on"))

    def test_lightbar_command_generation(self):
        """Checks lightbar color and brightness argument formatting."""
        # Simple RGB
        self.wrapper._command_history.clear()
        self.wrapper.set_lightbar_color(10, 20, 30, device_id="hidraw0")
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl -d hidraw0 lightbar 10 20 30")

        # RGB + Brightness
        self.wrapper._command_history.clear()
        self.wrapper.set_lightbar_color(255, 128, 0, brightness=200, device_id="hidraw1")
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl -d hidraw1 lightbar 255 128 0 200")

        # Bounds clamping (exceeding 255 or below 0)
        self.wrapper._command_history.clear()
        self.wrapper.set_lightbar_color(999, -50, 300, brightness=-10)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl lightbar 255 0 255 0")

    def test_led_brightness_command(self):
        """Checks led-brightness accepts 0, 1, 2."""
        for level in [0, 1, 2]:
            self.wrapper._command_history.clear()
            self.wrapper.set_led_brightness(level)
            self.assertEqual(self.wrapper._command_history[-1], f"dualsensectl led-brightness {level}")

    def test_player_leds_command(self):
        """Checks player-leds formatting and instant flag."""
        for p in range(0, 6):
            self.wrapper._command_history.clear()
            self.wrapper.set_player_leds(p, instant=True)
            self.assertEqual(self.wrapper._command_history[-1], f"dualsensectl player-leds {p} instant")

    def test_microphone_commands(self):
        """Checks microphone toggle, LED modes and routing modes."""
        self.wrapper._command_history.clear()
        self.wrapper.set_microphone(True)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl microphone on")

        self.wrapper.set_microphone(False)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl microphone off")

        for state in [MicLedState.ON, MicLedState.OFF, MicLedState.PULSE]:
            self.wrapper._command_history.clear()
            self.wrapper.set_microphone_led(state)
            self.assertEqual(self.wrapper._command_history[-1], f"dualsensectl microphone-led {state.value}")

        for mode in [MicMode.CHAT, MicMode.ASR, MicMode.BOTH]:
            self.wrapper._command_history.clear()
            self.wrapper.set_microphone_mode(mode)
            self.assertEqual(self.wrapper._command_history[-1], f"dualsensectl microphone-mode {mode.value}")

    def test_speaker_and_volume_commands(self):
        """Checks speaker destinations, volume and haptic attenuation."""
        for spk in [SpeakerMode.INTERNAL, SpeakerMode.HEADPHONE, SpeakerMode.BOTH]:
            self.wrapper._command_history.clear()
            self.wrapper.set_speaker(spk)
            self.assertEqual(self.wrapper._command_history[-1], f"dualsensectl speaker {spk.value}")

        self.wrapper._command_history.clear()
        self.wrapper.set_volume(200)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl volume 200")

        self.wrapper._command_history.clear()
        self.wrapper.set_attenuation(3, 5)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl attenuation 3 5")

    def test_all_7_trigger_modes_syntax(self):
        """Validates parameter generation and range enforcement for all 7 trigger modes."""
        # 1. Off
        self.wrapper._command_history.clear()
        self.wrapper.set_trigger_off(TriggerTarget.LEFT)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl trigger left off")

        # 2. Feedback (position: 0-9, strength: 1-8)
        self.wrapper._command_history.clear()
        self.wrapper.set_trigger_feedback(position=3, strength=7, target=TriggerTarget.RIGHT)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl trigger right feedback 3 7")

        # 3. Weapon (start: 2-7, stop: start+1..8, strength: 1-8)
        self.wrapper._command_history.clear()
        self.wrapper.set_trigger_weapon(start=2, stop=6, strength=8, target=TriggerTarget.BOTH)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl trigger both weapon 2 6 8")

        # 4. Bow (start: 0-8, stop: start+1..8, strength: 1-8, snap_force: 1-8)
        self.wrapper._command_history.clear()
        self.wrapper.set_trigger_bow(start=1, stop=7, strength=6, snap_force=8, target=TriggerTarget.BOTH)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl trigger both bow 1 7 6 8")

        # 5. Galloping (start: 0-8, stop: start+1..9, foot1: 0-8, foot2: foot1+1..8, freq: 1-8)
        self.wrapper._command_history.clear()
        self.wrapper.set_trigger_galloping(start=0, stop=8, first_foot=2, second_foot=5, frequency=4)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl trigger both galloping 0 8 2 5 4")

        # 6. Machine (start: 1-8, stop: start+1..8, strength_a: 0-7, strength_b: 0-7, freq, period)
        self.wrapper._command_history.clear()
        self.wrapper.set_trigger_machine(start=1, stop=7, strength_a=2, strength_b=7, frequency=12, period=2)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl trigger both machine 1 7 2 7 12 2")

        # 7. Vibration (position: 0-9, amplitude: 1-8, frequency: 1-40)
        self.wrapper._command_history.clear()
        self.wrapper.set_trigger_vibration(position=3, amplitude=6, frequency=24)
        self.assertEqual(self.wrapper._command_history[-1], "dualsensectl trigger both vibration 3 6 24")


class TestUIAndDispatch(unittest.TestCase):
    """
    Validates end-to-end interactions inside the PyQt6 UI widgets.
    """

    @classmethod
    def setUpClass(cls):
        cls.app = QApplication.instance() or QApplication(sys.argv)

    def setUp(self):
        self.wrapper = DualSenseCTLWrapper(executable_path="dualsensectl", simulation_mode=True)
        self.window = MainWindow(self.wrapper)
        self.wrapper._command_history.clear()

    def tearDown(self):
        self.window.monitor_worker.stop()
        self.window.close()

    def test_battery_widget_levels_and_labels(self):
        """Verifies battery states render proper badges, percentages, and hints."""
        # 1. Charging state
        bat_charging = BatteryInfo(percentage=45, status=BatteryStatus.CHARGING, status_text="charging")
        self.window.battery_widget.update_battery(bat_charging)
        self.assertEqual(self.window.battery_widget.label_pct.text(), "45%")
        self.assertIn("CHARGING", self.window.battery_widget.label_status.text())

        # 2. Low battery state (<20%)
        bat_low = BatteryInfo(percentage=12, status=BatteryStatus.DISCHARGING, status_text="discharging")
        self.window.battery_widget.update_battery(bat_low)
        self.assertEqual(self.window.battery_widget.label_pct.text(), "12%")
        self.assertIn("Connect USB", self.window.battery_widget.label_hint.text())

        # 3. Full battery state
        bat_full = BatteryInfo(percentage=100, status=BatteryStatus.FULL, status_text="full")
        self.window.battery_widget.update_battery(bat_full)
        self.assertEqual(self.window.battery_widget.label_pct.text(), "100%")
        self.assertEqual(self.window.battery_widget.label_status.text(), "FULL")

    def test_lightbar_preset_swatches_click(self):
        """Verifies that clicking every preset color updates the wrapper and preview."""
        for name, hex_code in PRESET_COLORS:
            self.wrapper._command_history.clear()
            self.window.lightbar_widget._apply_hex_color(hex_code)
            self.assertTrue(len(self.wrapper._command_history) > 0)
            last_cmd = self.wrapper._command_history[-1]
            self.assertIn("lightbar", last_cmd)
            self.assertEqual(self.window.lightbar_widget.lbl_color_hex.text(), hex_code.upper())

    def test_triggers_gaming_presets_dispatch(self):
        """Verifies each trigger gaming preset selects the right mode and dispatches."""
        preset_tests = [
            ("handgun", "weapon"),
            ("shotgun", "weapon"),
            ("sniper", "feedback"),
            ("bow", "bow"),
            ("machine_gun", "machine"),
            ("gallop", "galloping"),
            ("engine", "vibration"),
            ("off", "off"),
        ]

        for preset_id, expected_mode in preset_tests:
            self.wrapper._command_history.clear()
            idx = self.window.triggers_widget.combo_presets.findData(preset_id)
            self.assertGreaterEqual(idx, 0, f"Preset {preset_id} not found in dropdown")
            self.window.triggers_widget.combo_presets.setCurrentIndex(idx)
            self.window.triggers_widget.apply_current_trigger_config()
            last_cmd = self.wrapper._command_history[-1]
            self.assertIn(f"trigger both {expected_mode}", last_cmd)

    def test_microphone_mute_and_led_state(self):
        """Verifies mic mute toggle synchronizes mic command and orange LED indicator."""
        # Click Mute
        self.wrapper._command_history.clear()
        self.window.audio_widget._on_toggle_mic_mute()
        self.assertTrue(self.window.audio_widget.is_mic_muted)
        # Should have turned mic off and mic-led on
        commands_str = " ".join(self.wrapper._command_history)
        self.assertIn("microphone off", commands_str)
        self.assertIn("microphone-led on", commands_str)

        # Click Unmute
        self.wrapper._command_history.clear()
        self.window.audio_widget._on_toggle_mic_mute()
        self.assertFalse(self.window.audio_widget.is_mic_muted)
        commands_str = " ".join(self.wrapper._command_history)
        self.assertIn("microphone on", commands_str)
        self.assertIn("microphone-led off", commands_str)

    def test_firmware_dialog_content(self):
        """Verifies firmware dialog extracts and presents hardware and build info."""
        from PyQt6.QtWidgets import QDialog
        with patch.object(self.window.wrapper, "get_firmware_info") as mock_info, \
             patch.object(QDialog, "exec", return_value=1):
            from dualsensectl_gui.core.models import FirmwareInfo
            mock_info.return_value = FirmwareInfo(
                hardware="0x03",
                build_date="Oct 20 2024",
                firmware="0x0284",
                fw_version="2 134 0",
                raw_text="Test Firmware Raw Output"
            )
            # Invoke dialog creation
            self.window._show_firmware_dialog()


if __name__ == "__main__":
    unittest.main()
